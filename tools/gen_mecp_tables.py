"""Generate src/mecp_tables.h and tests/mecp_vectors.h from an MECP checkout.

    git clone https://github.com/mecp-org/MECP /tmp/mecp
    python3 tools/gen_mecp_tables.py /tmp/mecp

The language strings come from MECP's languages/*.json (CC BY 4.0, see
docs/USE.md "MECP"); the test vectors from freetext/tests.json. Only the packs
for languages the UI also speaks are compiled in -- the rest of the UI could not
be read in them anyway -- and a build without I18N_ENABLED keeps English alone.
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# MECP pack code -> UiLang enumerator (src/i18n.h). Order sets the table order.
PACKS = [
    ("en", "LANG_EN"), ("es", "LANG_ES"), ("fr", "LANG_FR"), ("it", "LANG_IT"),
    ("de", "LANG_DE"), ("pt", "LANG_PT"), ("pl", "LANG_PL"), ("nl", "LANG_NL"),
    ("cs", "LANG_CS"), ("sv", "LANG_SV"), ("no", "LANG_NB"), ("sk", "LANG_SK"),
    ("tr", "LANG_TR"),
]

# UI strings the firmware draws from the packs, in MecpUi order (src/mecp.h).
UI_KEYS = ["person_count", "beacon_active", "beacon_drill", "unknown_code"]

# The device fonts cover ASCII, Latin-1 and Latin Extended-A (tools/
# gen_latin_fonts.sh); these are the only characters the packs use outside it.
FOLD = {"\u2014": "-", "\u2013": "-", "\u2019": "'", "\u2018": "'",
        "\u201c": '"', "\u201d": '"', "\u2026": "..."}


def font_ok(ch):
    c = ord(ch)
    return 0x20 <= c <= 0x7E or 0xA0 <= c <= 0x17F or 0x218 <= c <= 0x21B


def fold(s, where):
    out = "".join(FOLD.get(ch, ch) for ch in s)
    bad = sorted({ch for ch in out if not font_ok(ch)})
    if bad:
        sys.exit(f"{where}: no glyph for {', '.join(f'U+{ord(c):04X}' for c in bad)}; add it to FOLD")
    return out


def c_str(s):
    # Octal escapes are at most three digits, so a following digit is safe.
    out = []
    for b in s.encode("utf-8"):
        if b in (0x22, 0x5C):
            out.append("\\" + chr(b))
        elif 0x20 <= b < 0x7F:
            out.append(chr(b))
        else:
            out.append(f"\\{b:03o}")
    return '"' + "".join(out) + '"'


def describe(src):
    version = json.loads((src / "freetext" / "manifest.json").read_text("utf-8"))["protocolVersion"]
    try:
        commit = subprocess.check_output(
            ["git", "-C", str(src), "rev-parse", "--short", "HEAD"], text=True).strip()
    except (OSError, subprocess.CalledProcessError):
        commit = "unknown"
    return f"{version} ({commit})"


def gen_tables(src, rev):
    packs = {code: json.loads((src / "languages" / f"{code}.json").read_text("utf-8"))
             for code, _ in PACKS}
    en = packs["en"]
    cats = list(en["categories"].keys())
    codes = list(en["codes"].keys())
    for code, pack in packs.items():
        if list(pack["codes"].keys()) != codes or list(pack["categories"].keys()) != cats:
            sys.exit(f"{code}.json: code or category list differs from en.json")

    L = []
    L.append("// SPDX-License-Identifier: GPL-3.0-or-later AND CC-BY-4.0")
    L.append("// Generated by tools/gen_mecp_tables.py from MECP " + rev + " -- do not edit.")
    L.append("// Strings: MECP language packs, CC BY 4.0, (c) the MECP contributors,")
    L.append("// https://github.com/mecp-org/MECP. Changed: typographic dashes and quotes")
    L.append("// folded to ASCII for the device fonts; only these languages are included.")
    L.append("#pragma once")
    L.append("")
    L.append(f"static constexpr int kMecpCategoryCount = {len(cats)};")
    L.append(f"static constexpr int kMecpCodeCount = {len(codes)};")
    L.append(f"static constexpr int kMecpUiCount = {len(UI_KEYS)};")
    L.append("static const char kMecpCategoryLetters[kMecpCategoryCount + 1] = " + c_str("".join(cats)) + ";")
    L.append("// Codes in table order, grouped by category; three characters each.")
    L.append("static const char kMecpCodes[kMecpCodeCount * 3 + 1] =")
    for i in range(0, len(codes), 12):
        L.append("    " + c_str("".join(codes[i:i + 12])))
    L[-1] += ";"
    L.append("")
    L.append("struct MecpPack {")
    L.append("    uint8_t     uiLang;")
    L.append("    const char *packCode;")
    L.append("    const char *severity[4];")
    L.append("    const char *category[kMecpCategoryCount];")
    L.append("    const char *code[kMecpCodeCount];")
    L.append("    const char *ui[kMecpUiCount];")
    L.append("};")
    L.append("")
    L.append("static const MecpPack kMecpPacks[] = {")
    for code, enum in PACKS:
        p = packs[code]
        if code == PACKS[1][0]:
            L.append("#if I18N_ENABLED")
        w = f"{code}.json"
        L.append(f"    {{ {enum}, {c_str(code)},")
        L.append("      { " + ", ".join(c_str(fold(p["severities"][str(i)]["local"], w)) for i in range(4)) + " },")
        L.append("      {")
        for c in cats:
            L.append(f"        {c_str(fold(p['categories'][c]['name'], w))},")
        L.append("      },")
        L.append("      {")
        for c in codes:
            L.append(f"        {c_str(fold(p['codes'][c], w))},  // {c}")
        L.append("      },")
        L.append("      { " + ", ".join(c_str(fold(p["ui"].get(k, en["ui"][k]), w)) for k in UI_KEYS) + " },")
        L.append("    },")
    L.append("#endif  // I18N_ENABLED")
    L.append("};")
    L.append("")
    return "\n".join(L)


def gen_vectors(src, rev):
    tests = json.loads((src / "freetext" / "tests.json").read_text("utf-8"))
    L = []
    L.append("// SPDX-License-Identifier: GPL-3.0-or-later AND CC0-1.0")
    L.append("// Generated by tools/gen_mecp_tables.py from MECP " + rev + " freetext/tests.json")
    L.append("// (CC0) -- do not edit.")
    L.append("#pragma once")
    L.append("")
    L.append("struct MecpVector {")
    L.append("    const char *title;")
    L.append("    const char *input;")
    L.append("    bool        valid;")
    L.append("    const char *timestamp;   // \"HH:MM\" or nullptr")
    L.append("    const char *reference;")
    L.append("    long        pax;         // -1: absent")
    L.append("    bool        hasGps;")
    L.append("    double      lat, lon;")
    L.append("    const char *callsign;")
    L.append("    const char *language;")
    L.append("    long        duration;    // minutes, -1: absent")
    L.append("};")
    L.append("")
    L.append("static const MecpVector kMecpVectors[] = {")

    def s(v):
        return "nullptr" if v is None else c_str(v)

    for t in tests:
        e = t["expect"]
        valid = e is not None
        e = e or {}
        known = {"timestamp", "reference", "pax", "gps", "callsign", "language", "duration"}
        if set(e) - known:
            sys.exit(f"{t['title']}: unknown expect keys {set(e) - known}")
        gps = e.get("gps")
        L.append("    { " + ", ".join([
            c_str(t["title"]), c_str(t["input"]), "true" if valid else "false",
            s(e.get("timestamp")), s(e.get("reference")),
            str(e["pax"]) if e.get("pax") is not None else "-1",
            "true" if gps else "false",
            repr(float(gps["lat"])) if gps else "0", repr(float(gps["lon"])) if gps else "0",
            s(e.get("callsign")), s(e.get("language")),
            str(e["duration"]) if e.get("duration") is not None else "-1",
        ]) + " },")
    L.append("};")
    L.append("")
    return "\n".join(L)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = Path(sys.argv[1])
    rev = describe(src)
    (ROOT / "src" / "mecp_tables.h").write_text(gen_tables(src, rev), "utf-8")
    (ROOT / "tests" / "mecp_vectors.h").write_text(gen_vectors(src, rev), "utf-8")
    print(f"wrote src/mecp_tables.h and tests/mecp_vectors.h from MECP {rev}")


if __name__ == "__main__":
    main()
