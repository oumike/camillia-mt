#!/usr/bin/env node
// Generates src/community_presets.{h,cpp} from PROFILES in camillia-mt-web's
// src/customize.js, so the firmware offers exactly the community setups the
// web flasher's Customize dialog does -- minus the logos, which the firmware
// cannot draw from a URL.
//
//   node tools/gen_community_presets.mjs [path/to/camillia-mt-web]
//
// The web repo defaults to ../camillia-mt-web. Re-run after PROFILES changes
// there and commit the two files it writes.

import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs'
import { join, resolve, dirname } from 'node:path'
import { tmpdir } from 'node:os'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repo = resolve(here, '..')
const webRepo = resolve(process.argv[2] || join(repo, '..', 'camillia-mt-web'))
const source = join(webRepo, 'src', 'customize.js')

// customize.js imports withBase() from a module that reads Vite's
// import.meta.env, which plain node does not have. Only the logos use it, and
// they are dropped, so it is stubbed out and the rest loaded as written.
const text = readFileSync(source, 'utf8').replace(
  /^import \{ withBase \} from '\.\/basePath'.*$/m,
  'const withBase = p => p',
)
const tmp = mkdtempSync(join(tmpdir(), 'community-presets-'))
let PROFILES
try {
  const mod = join(tmp, 'customize.mjs')
  writeFileSync(mod, text)
  ;({ PROFILES } = await import(pathToFileURL(mod).href))
} finally {
  rmSync(tmp, { recursive: true, force: true })
}

const str = s => JSON.stringify(s ?? '')
  // Keep the header ASCII: anything else becomes a UTF-8 escape C++ reads back
  // byte for byte. JSON's own escapes (\" \\ \n) are valid C++ as they are.
  .replace(/[^\x00-\x7f]/g, ch => Array.from(Buffer.from(ch, 'utf8'), b => `\\x${b.toString(16)}""`).join(''))
const flag = b => (b ? 'true' : 'false')

const chanLines = []
const presetLines = []
for (const p of PROFILES) {
  const first = chanLines.length
  for (const c of p.channels) {
    chanLines.push(`    { ${str(c.name.trim())}, ${str(c.psk.trim())}, ${flag(c.pos)}, ${flag(c.up)}, ${flag(c.down)} },`)
  }
  presetLines.push(
    `    { ${str(p.id)}, ${str(p.area)}, ${str(p.label)}, ${str(p.url)},\n` +
    `      ${str(p.preset)}, ${p.slot || 0}, ${str(p.region)}, ${first}, ${p.channels.length},\n` +
    `      ${str(p.notes)} },`,
  )
}

const out = `#pragma once
// GENERATED by tools/gen_community_presets.mjs from PROFILES in
// camillia-mt-web/src/customize.js. Do not edit by hand: change the web repo's
// list and re-run the generator, so the flasher and the firmware stay the same.
//
// Community setups, as published by each mesh: the radio preset (empty = keep
// the device's own), a frequency slot (0 = the preset's own), the region and a
// whole channel plan. Applied through the \`cfg\` CLI's staging and commit
// (communityPresetApply() in main_lvgl.cpp), which replaces every channel.
#include <stdint.h>

struct CommunityPresetChannel {
    const char *name;   // empty on the primary = named after the preset
    const char *psk;    // "default", "none" or base64 (1, 16 or 32 bytes)
    bool pos;
    bool up;
    bool down;
};

struct CommunityPreset {
    const char *id;
    const char *area;
    const char *label;
    const char *url;
    const char *preset;   // kPresets[].channelName, or "" to keep the device's
    uint8_t slot;
    const char *region;   // kRegions[].code
    uint16_t firstChannel;
    uint8_t channelCount;
    const char *notes;    // what the community also advises, set by hand
};

extern const CommunityPresetChannel kCommunityPresetChannels[];
extern const CommunityPreset kCommunityPresets[];
extern const int kCommunityPresetCount;

// Implemented in main_lvgl.cpp. Why preset \`idx\` cannot be applied on this
// device (too many channels, a preset this radio cannot run, a slot outside
// its region), or nullptr when it can.
const char *communityPresetProblem(int idx);
`
const data = `// GENERATED by tools/gen_community_presets.mjs from PROFILES in
// camillia-mt-web/src/customize.js. Do not edit by hand.
#include "community_presets.h"

const CommunityPresetChannel kCommunityPresetChannels[] = {
${chanLines.join('\n')}
};

const CommunityPreset kCommunityPresets[] = {
${presetLines.join('\n')}
};

const int kCommunityPresetCount =
    (int)(sizeof(kCommunityPresets) / sizeof(kCommunityPresets[0]));
`
writeFileSync(join(repo, 'src', 'community_presets.h'), out)
writeFileSync(join(repo, 'src', 'community_presets.cpp'), data)
console.log(`wrote src/community_presets.{h,cpp}: ${PROFILES.length} presets, ${chanLines.length} channels`)
