/*******************************************************************************
 * Montserrat Bold 12 px, ASCII 0x20-0x7E plus Latin-1/Extended-A, Romanian
 * comma-below S/T and the euro sign (issue #99), for the sleep-overlay
 * message rows. LVGL 9.5 ships Montserrat Medium only and has no synthetic
 * bold, so the heavier half of each row needs a face of its own.
 *
 * Built only into environments that draw the sleep/lock overlay (see
 * build_src_filter in platformio.ini); Cardputer does not carry the glyphs.
 *
 * Montserrat is SIL OFL 1.1, the same face LVGL's own built-ins are cut from.
 *
 * Regenerate:
 *   Montserrat-Bold.ttf from github.com/JulietaUla/Montserrat (fonts/ttf; the
 *   static weight-700 cut, equivalent to instancing Montserrat[wght] at 700)
 *   npx lv_font_conv@1.5.3 --no-compress --no-prefilter --bpp 4 --size 12 \
 *       --font Montserrat-Bold.ttf -r 0x20-0x7E,0xA0-0x17F,0x218-0x21B,0x20AC \
 *       --format lvgl --force-fast-kern-format -o lv_font_montserrat_bold_12.c
 *   then replace the generated include block with <lvgl.h>.
 *
 * The generated line_height (17) and base_line (4) do NOT match
 * lv_font_montserrat_12 (15/3). Two labels sharing a row must share a
 * baseline, so tdeckProBoldRowFont() overrides both at runtime rather than
 * hand-editing them here, where a regeneration would silently drop the fix.
 * Do not hand-edit.
 ******************************************************************************/

